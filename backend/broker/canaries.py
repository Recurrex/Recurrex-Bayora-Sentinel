"""Canary detection.

Canaries are fake secrets planted in the sandbox (generated by Aritraa) so any
leak through the broker is detectable.  The broker reads them from
CANARIES_PATH (default /etc/sentinel/canaries.json), format:

    {"canaries": ["SNTL-CANARY-...", "..."]}

CANARIES_PATH is re-read on every scan so the sandbox can rotate canaries
mid-session and tests can inject their own list.
"""

import json
import logging
import os

log = logging.getLogger("sentinel.canaries")

DEFAULT_CANARIES_PATH = "/etc/sentinel/canaries.json"


def load_canaries() -> list[str]:
    """Return the current canary list (empty if the file is missing/bad).

    Canary values are secrets-of-a-sort: never log them, only counts.
    """
    path = os.environ.get("CANARIES_PATH", DEFAULT_CANARIES_PATH)
    try:
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
    except OSError:
        log.info("canaries file not present at %s; detection disabled", path)
        return []
    except ValueError:
        log.info("canaries file is not valid JSON; detection disabled")
        return []
    canaries = data.get("canaries", []) if isinstance(data, dict) else []
    if not isinstance(canaries, list):
        return []
    cleaned = [c for c in canaries if isinstance(c, str) and c]
    log.info("loaded %d canaries", len(cleaned))
    return cleaned


def scan(text: str) -> list[str]:
    """Return the canary strings found in `text` (exact substring match)."""
    if not text:
        return []
    hits = []
    for canary in load_canaries():
        if canary in text:
            hits.append(canary)
    if hits:
        log.info("canary scan hit: %d canary value(s) present", len(hits))
    return hits


def mask(text: str, hits: list[str]) -> str:
    """Replace every occurrence of each hit with [CANARY]."""
    for canary in hits:
        text = text.replace(canary, "[CANARY]")
    return text
